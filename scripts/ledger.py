#!/usr/bin/env python3
"""The ledger writer. Runs ONLY on main, only in CI.

Two files per merged MR under ledger/mr-<iid>/, plus a generated LEDGER.md:

  certificate.md  immutable pre-merge evidence. Written once, hash recorded.
  events.md       append-only post-merge history, each entry referencing the
                  certificate hash.

Splitting them is what lets the record describe production events that happen
after certification without ever changing what was certified.

No agent has write access to any of this. Nothing is ever committed to an MR
branch by the ledger.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

LEDGER = Path("ledger")


def utcnow() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def commit_certificate(mr_iid: str, certificate_md: str) -> str:
    """Write the certificate once. Refuse to overwrite an existing one."""
    d = LEDGER / f"mr-{mr_iid}"
    d.mkdir(parents=True, exist_ok=True)
    cert = d / "certificate.md"

    digest = hashlib.sha256(certificate_md.encode()).hexdigest()

    if cert.exists():
        existing = hashlib.sha256(cert.read_bytes()).hexdigest()
        if existing != digest:
            raise SystemExit(
                f"REFUSED: ledger/mr-{mr_iid}/certificate.md already exists with "
                f"hash {existing[:8]} and would be overwritten by {digest[:8]}. "
                "A certificate is immutable once written."
            )
        return digest

    cert.write_text(certificate_md)
    (d / "certificate.sha256").write_text(digest)

    events = d / "events.md"
    if not events.exists():
        events.write_text(
            f"# Events · MR !{mr_iid}\n\n"
            f"Append-only post-merge history. Every entry references the "
            f"certificate hash `{digest[:12]}`.\n\n"
            f"| When | Event | Detail | Identity | Certificate |\n"
            f"| --- | --- | --- | --- | --- |\n"
        )

    return digest


def append_event(
    mr_iid: str, event: str, detail: str, identity: str, cert_hash: str
) -> None:
    """Append one post-merge event. Never modifies an existing line."""
    events = LEDGER / f"mr-{mr_iid}" / "events.md"
    if not events.exists():
        raise SystemExit(
            f"REFUSED: no events.md for MR !{mr_iid}. The certificate must be "
            "committed before any event is appended."
        )
    with events.open("a") as f:
        f.write(
            f"| {utcnow()} | {event} | {detail} | {identity} | `{cert_hash[:12]}` |\n"
        )


def regenerate_index() -> None:
    """Rewrite LEDGER.md from what is on disk. Generated, never hand-edited."""
    entries = []
    for d in sorted(LEDGER.glob("mr-*"), key=lambda p: int(p.name.split("-")[1])):
        cert = d / "certificate.md"
        if not cert.exists():
            continue
        head = cert.read_text().splitlines()
        title = head[0].removeprefix("# Certificate · ").strip() if head else d.name
        status = next(
            (ln.split("Status: ")[1].split(" ")[0] for ln in head if "Status: " in ln),
            "?",
        )
        digest = hashlib.sha256(cert.read_bytes()).hexdigest()
        iid = d.name.split("-")[1]
        n_events = max(0, len((d / "events.md").read_text().splitlines()) - 6) \
            if (d / "events.md").exists() else 0
        entries.append(
            f"| [!{iid}]({d.name}/certificate.md) | {title} | {status} | "
            f"`{digest[:12]}` | {n_events} |"
        )

    Path("LEDGER.md").write_text(
        f"""# Ledger

A complete record of claims, evidence, and human rulings — tied to the exact
commits and artifacts it describes.

Every row is one merged merge request. The certificate is the immutable
pre-merge evidence record; events are the append-only post-merge history.
Both are written only by CI on `main`. No agent has write access.

Generated by `scripts/ledger.py`. Do not hand-edit.

| MR | Title | Status | Certificate hash | Events |
| --- | --- | --- | --- | --- |
{chr(10).join(entries) if entries else "| — | _no entries yet_ | | | |"}

---

**Unsupported functional findings across every entry above: 0.** That is the
one thing this record is designed to guarantee. It does not guarantee that
every finding was a real defect — a sustained contest means the human ruled
that an experiment encoded the wrong spec, and those are counted here too.

Last regenerated: {utcnow()}
"""
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest="cmd", required=True)

    c = sub.add_parser("commit", help="write the certificate for a merged MR")
    c.add_argument("--mr-iid", required=True)
    c.add_argument("--certificate", required=True, help="path to certificate.md")

    e = sub.add_parser("event", help="append a post-merge event")
    e.add_argument("--mr-iid", required=True)
    e.add_argument("--event", required=True,
                   help="deploy-staging | deploy-prod | approval | watch | motion | rollback")
    e.add_argument("--detail", required=True)
    e.add_argument("--identity", required=True)
    e.add_argument("--cert-hash", required=True)

    sub.add_parser("index", help="regenerate LEDGER.md")

    args = ap.parse_args()

    if args.cmd == "commit":
        md = Path(args.certificate).read_text()
        digest = commit_certificate(args.mr_iid, md)
        regenerate_index()
        print(f"certificate committed: ledger/mr-{args.mr_iid}/certificate.md")
        print(f"hash: {digest}")
        return 0

    if args.cmd == "event":
        append_event(args.mr_iid, args.event, args.detail, args.identity,
                     args.cert_hash)
        regenerate_index()
        print(f"event appended to ledger/mr-{args.mr_iid}/events.md")
        return 0

    regenerate_index()
    print("LEDGER.md regenerated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
