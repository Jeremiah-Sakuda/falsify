#!/usr/bin/env bash
# The promote job. HUMAN-RUN, manual, never automatic.
#
# GitLab suggestions can only change lines already in the diff and cannot
# create a file, so this job copies the experiment BYTE-FOR-BYTE into tests/
# and records its hash. The certificate job then verifies the file is present
# at the MR head with that exact hash.
#
# The push uses a PROJECT ACCESS TOKEN, not CI_JOB_TOKEN — a CI_JOB_TOKEN push
# would not start a pipeline, and the new pipeline is what re-certifies.
#
# Usage: promote.sh <experiment-id>   (e.g. promote.sh X2)
set -euo pipefail

EID="${1:?usage: promote.sh <experiment-id>, e.g. X2}"
SCRATCH="falsify/mr-${CI_MERGE_REQUEST_IID:?not an MR pipeline}"
SRC=".falsify/experiments/$(echo "${EID}" | tr '[:upper:]' '[:lower:]')_test.py"

: "${FALSIFY_PROMOTE_TOKEN:?project access token required; CI_JOB_TOKEN cannot start a pipeline}"

echo "Promoting ${EID} from ${SCRATCH}"

git fetch --depth=1 origin "${SCRATCH}"
git checkout "origin/${SCRATCH}" -- "${SRC}"

if [ ! -f "${SRC}" ]; then
  echo "REFUSED: ${SRC} not found on ${SCRATCH}" >&2
  exit 1
fi

# Derive the permanent name from the experiment's docstring target, falling
# back to the experiment id. Byte-for-byte copy either way.
DEST="tests/test_${EID,,}_promoted.py"
cp "${SRC}" "${DEST}"

HASH="$(sha256sum "${DEST}" | cut -d' ' -f1)"
echo "${EID} ${DEST} ${HASH}" >> .falsify/promotions.txt

git config user.name  "falsify-promote"
git config user.email "promote@falsify.invalid"
git add "${DEST}" .falsify/promotions.txt
git commit -m "promote ${EID}: ${DEST}

Promoted by ${GITLAB_USER_LOGIN:-unknown} running the manual promote job.
Experiment digest recorded in the certificate. Do not edit this file — its
hash is evidence.

sha256: ${HASH}"

ORIGIN="https://promote:${FALSIFY_PROMOTE_TOKEN}@${CI_SERVER_HOST}/${CI_PROJECT_PATH}.git"
git push "${ORIGIN}" "HEAD:${CI_MERGE_REQUEST_SOURCE_BRANCH_NAME}"

echo
echo "Promoted ${EID} -> ${DEST}"
echo "sha256: ${HASH}"
echo "A new MR pipeline will re-certify. The finding resolves only when the"
echo "rerun is green AND this file is present at the head with this hash."
